    private void saveButton_actionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveButton_actionPerformed
        if (this.selectedItem.isEmpty()) {
            MessageUtils.showInformationMessage("Invalid operation", "Please select a user to update!");
            return;
        }
        
        if (!this.formValid()) {
            return;
        }
        
        try {
            var item = this.selectedItem.get();
            var username = this.usernameField.getText().trim();
            item.setUsername(username);
            
            var itemRepo = this.repository.getUserRepo();
            var existingUser = itemRepo.getByUsername(username);
            if (existingUser.isPresent() && !existingUser.get().equals(item)) {
                MessageUtils.showErrorMessage("Error", "A user with the username '" + username + "' already exists!");
                return;
            }
            
            item.setRole(this.roleComboBoxModel.getSelectedItem());
            
            itemRepo.update(item);
            
            this.clearForm();
            this.itemTableModel.set(itemRepo.getAll());
        } catch (Exception ex) {
            Logger.getLogger(UsersView.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Failed to update user!");
        }
    }//GEN-LAST:event_saveButton_actionPerformed

    private void deleteButton_actionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButton_actionPerformed
        if (this.selectedItem.isEmpty()) {
            MessageUtils.showInformationMessage("Invalid operation", "Please select a user to update!");
            return;
        }
        
        try {
            var item = this.selectedItem.get();
            var itemRepo = this.repository.getUserRepo();
            itemRepo.delete(item);
            
            this.clearForm();
            this.itemTableModel.set(itemRepo.getAll());
            
            MessageUtils.showInformationMessage("Success", "User deleted.");
        } catch (Exception ex) {
            Logger.getLogger(UsersView.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Failed to update user!");
        }
    }//GEN-LAST:event_deleteButton_actionPerformed

