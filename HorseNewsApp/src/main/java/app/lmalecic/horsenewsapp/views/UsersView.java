    private void initValidation() {
        this.validationFields = Arrays.asList(
                this.usernameField
        );
        
        this.errorLabels = HashMap.newHashMap(this.validationFields.size());
        this.errorLabels.put(this.usernameField, this.usernameErrorLabel);
    }

    private void hideErrors() {
        this.errorLabels.forEach((key, label) -> {
            label.setVisible(false);
            label.setToolTipText("");
        });
    }

    private void initRepository() {
        this.repository = RepositoryFactory.get();
    }

    private void initTable() throws Exception {
        new Thread(() -> {
            try {
                this.usersTable.setAutoCreateRowSorter(true);
                this.itemTableModel = new UserTableModel(repository.getUserRepo().getAll());
                this.usersTable.setModel(this.itemTableModel);
            } catch (Exception ex) {
                Logger.getLogger(UsersView.class.getName()).log(Level.SEVERE, null, ex);
                MessageUtils.showErrorMessage("Error", "Failed to get users!");
            }
        }).start();
    }

    private void clearForm() {
        this.hideErrors();
        this.validationFields.forEach(e -> e.setText(""));
        this.selectedItem = Optional.empty();
    }

    private void initRoles() {
        new Thread(() -> {
            this.roleComboBoxModel = new RoleComboBoxModel(allRoles);
            this.roleComboBox.setModel(this.roleComboBoxModel);
        }).start();
    }
    
    private void showItem() {
        this.clearForm();
        int selectedRow = this.usersTable.getSelectedRow();
        int rowIndex = this.usersTable.convertRowIndexToModel(selectedRow);
        String selectedItemUsername = (String) this.itemTableModel.getValueAt(rowIndex, 1);

        try {
            Optional<User> optItem = this.repository.getUserRepo().getByUsername(selectedItemUsername);
            if (optItem.isPresent()) {
                this.selectedItem = optItem;
                this.fillForm(this.selectedItem);
            }
        } catch (Exception ex) {
            Logger.getLogger(UsersView.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Unable to show user!");
        }
    }
    
    private void fillForm(Optional<User> itemOpt) throws Exception {
        if (itemOpt.isEmpty())
            return;
        
        var item = itemOpt.get();
        this.usernameField.setText(item.getUsername());     
        this.roleComboBoxModel.setSelectedItem(item.getRole());
        this.roleComboBox.repaint();
    }
    
    private boolean formValid() {
        hideErrors();
        boolean ok = true;
        
        for (var label : this.validationFields) {
            boolean errorVisible = false;
            String errorText = "";
            
            String text = label.getText().trim();
            if (text.isEmpty()) {
                ok = false;
                errorVisible = true;
                errorText = "Cannot be empty!";
            } else if (label.equals(this.usernameField)) {
                try {
                    var user = repository.getUserRepo().getByUsername(text);
                    if (user.isPresent() && (this.selectedItem.isPresent() && !user.get().equals(this.selectedItem.get()))) {
                        ok = false;
                        errorVisible = true;
                        errorText = "A user with this username already exists!";
                    }
                } catch (Exception ex) {
                    ok = false;
                    errorVisible = true;
                    errorText = "Failed to check if user with this username already exists!";
                    Logger.getLogger(UsersView.class.getName()).log(Level.SEVERE, null, ex);
                    MessageUtils.showErrorMessage("Error", errorText);
                }
            }
            
            var errorLabel = this.errorLabels.get(label);
            if (errorLabel != null) {
                errorLabel.setToolTipText(errorText);
                errorLabel.setVisible(errorVisible);
            }
        }
        
        return ok;
    }
