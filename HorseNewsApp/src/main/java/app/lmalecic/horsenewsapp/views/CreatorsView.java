    private void addButton_actionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButton_actionPerformed
        if (!this.formValid()) {
            return;
        }
        
        try {
            var itemName = this.creatorNameField.getText().trim();
            
            var itemRepo = this.repository.getCreatorRepo();
            if (itemRepo.getByName(itemName).isPresent()) {
                MessageUtils.showErrorMessage("Error", "A creator with name '" + itemName + "' already exists!");
                return;
            }

            var newItem = new Creator(itemName);
            itemRepo.create(newItem);
            
            this.itemTableModel.set(itemRepo.getAll());
            this.clearForm();
        } catch (Exception ex) {
            Logger.getLogger(CreatorsView.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Failed to create creator!");
        }
    }//GEN-LAST:event_addButton_actionPerformed

    private void saveButton_actionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveButton_actionPerformed
                if (this.selectedItem.isEmpty()) {
            MessageUtils.showInformationMessage("Invalid operation", "Please select a creator to update!");
            return;
        }
        
        if (!this.formValid()) {
            return;
        }
        
        try {
            var item = this.selectedItem.get();
            var itemName = this.creatorNameField.getText().trim();
            item.setName(itemName);
            
            var itemRepo = this.repository.getCreatorRepo();
            if (itemRepo.getByName(itemName).isPresent()) {
                MessageUtils.showErrorMessage("Error", "A creator with name '" + itemName + "' already exists!");
                return;
            }
            
            itemRepo.update(item);
            
            this.itemTableModel.set(itemRepo.getAll());
            this.clearForm();
        } catch (Exception ex) {
            Logger.getLogger(CreatorsView.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Failed to update creator!");
        }
    }//GEN-LAST:event_saveButton_actionPerformed

    private void deleteButton_actionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButton_actionPerformed
        if (this.selectedItem.isEmpty()) {
            MessageUtils.showInformationMessage("Invalid operation", "Please select a creator to delete!");
            return;
        }
        
        try {
            var itemRepo = this.repository.getCreatorRepo();
            itemRepo.delete(this.selectedItem.get().getId());
            
            this.itemTableModel.set(itemRepo.getAll());
            this.clearForm();
            
            MessageUtils.showInformationMessage("Success", "Successfully deleted creator!");
        } catch (Exception ex) {
            Logger.getLogger(CreatorsView.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Failed to delete creator!");
        }
    }//GEN-LAST:event_deleteButton_actionPerformed

