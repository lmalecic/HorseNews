    private void entityXmlExportButton_actionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_entityXmlExportButton_actionPerformed
        if (this.selectedItem.isEmpty()) {
            MessageUtils.showInformationMessage("Export info", "Please select a creator to export!");
            return;
        }

        try {
            var exportItem = this.selectedItem.get();
            var file = FileUtils.saveFile("Export to XML", exportItem.getClass().getSimpleName() + "_" + exportItem.getName(), "xml");
            if (file.isEmpty()) {
                return;
            }

            JAXBUtils.save(exportItem, file.get());
        } catch (JAXBException ex) {
            Logger.getLogger(CreatorsView.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Export error", "Failed to export to xml!");
        }
    }//GEN-LAST:event_entityXmlExportButton_actionPerformed

    private void showItem() {
        this.clearForm();
        int selectedRow = this.creatorsTable.getSelectedRow();
        int rowIndex = this.creatorsTable.convertRowIndexToModel(selectedRow);
        int selectedItemId = (int) this.itemTableModel.getValueAt(rowIndex, 0);

        try {
            Optional<Creator> optItem = this.repository.getCreatorRepo().get(selectedItemId);
            if (optItem.isPresent()) {
                this.selectedItem = optItem;
                this.fillForm(this.selectedItem);
            }
        } catch (Exception ex) {
            Logger.getLogger(CreatorsView.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Unable to show creator!");
        }
    }

