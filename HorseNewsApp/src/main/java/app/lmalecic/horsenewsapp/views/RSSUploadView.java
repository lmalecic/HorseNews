    private void uploadButton_actionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_uploadButton_actionPerformed
        this.uploadButton.setEnabled(false);
        this.deleteAllButton.setEnabled(false);
        
        new Thread(() -> {
            try {
                var repo = RepositoryFactory.get();
                var articleRepo = repo.getArticleRepo();
                var categoryRepo = repo.getCategoryRepo();
                var creatorRepo = repo.getCreatorRepo();
                
                ArticleParser.parse().forEach(article -> {
                    try {
                        // Create creator if missing
                        var existingCreator = creatorRepo.getByName(article.getCreator().getName());
                        if (existingCreator.isEmpty()) {
                            creatorRepo.create(article.getCreator());
                        } else {
                            article.setCreator(existingCreator.get());
                        }
                        
                        // Create categories if missing
                        article.getCategories().forEach(category -> {
                            try {
                                var existingCategory = categoryRepo.getByName(category.getName());
                                if (existingCategory.isEmpty()) {
                                    categoryRepo.create(category);
                                } else {
                                    category.setId(existingCategory.get().getId());
                                }
                            } catch (Exception ex) {
                                Logger.getLogger(RSSUploadView.class.getName()).log(Level.SEVERE, null, ex);
                            }
                        });
                        
                        var existingArticle = articleRepo.getByGuid(article.getGuid());
                        if (existingArticle.isEmpty()) {
                            articleRepo.create(article);
                        } else {
                            article.setId(existingArticle.get().getId());
                            articleRepo.update(article);
                        }
                        
                        // Categories exist, add them to mapping table
                        article.getCategories().forEach(category -> {
                           try {
                               articleRepo.addCategory(article, category, false);
                           } catch (Exception ex) { 
                                Logger.getLogger(RSSUploadView.class.getName()).log(Level.SEVERE, null, ex);
                            } 
                        });
                        
                        articlesModel.addElement(article);
                    } catch (Exception ex) {
                        Logger.getLogger(RSSUploadView.class.getName()).log(Level.SEVERE, "Failed to create articles!", ex);
                        MessageUtils.showErrorMessage("Error", "Failed to upload articles!");
                    }
                });
            } catch (Exception ex) {
                Logger.getLogger(RSSUploadView.class.getName()).log(Level.SEVERE, null, ex);
                MessageUtils.showErrorMessage("Error", "Failed to upload articles!");
            }
            
            this.uploadButton.setEnabled(true);
            this.deleteAllButton.setEnabled(true);
        }).start();
    }//GEN-LAST:event_uploadButton_actionPerformed

    private void deleteAllButton_actionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteAllButton_actionPerformed
        this.deleteAllButton.setEnabled(false);
        this.uploadButton.setEnabled(false);
        
        try {
            RepositoryFactory.get().deleteAllData();
            
        } catch (Exception ex) {
            Logger.getLogger(RSSUploadView.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Failed to delete all data!");
        }
        
        articlesModel.clear();
        
        this.deleteAllButton.setEnabled(true);
        this.uploadButton.setEnabled(true);
    }//GEN-LAST:event_deleteAllButton_actionPerformed

