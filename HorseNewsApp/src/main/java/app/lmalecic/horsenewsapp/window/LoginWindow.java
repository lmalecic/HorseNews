    private void loginButton_actionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginButton_actionPerformed
        new Thread(() -> {
            try {
                String username = this.usernameField.getText().trim();
                String password = new String(this.passwordField.getPassword());
                Optional<User> user = RepositoryFactory.get().getUserRepo().login(username, password);
                
                if (user.isPresent()) {
                    HorseNewsApp.performLogIn(user.get());
                } else {
                    MessageUtils.showErrorMessage("Login failed", "User doesn't exist or incorrect password!");
                }
            } catch (Exception ex) {
                Logger.getLogger(LoginWindow.class.getName()).log(Level.SEVERE, null, ex);
            }
        }).start();
    }//GEN-LAST:event_loginButton_actionPerformed

    private void registerButton_actionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerButton_actionPerformed
        new Thread(() -> {
            try {
                String username = this.usernameField.getText().trim();
                String password = new String(this.passwordField.getPassword());
                User user = RepositoryFactory.get().getUserRepo().register(username, password);
                HorseNewsApp.performLogIn(user);
            } catch (UserAlreadyExistsException ex) {
                MessageUtils.showErrorMessage("Registration failed", ex.getMessage());
            } catch (Exception ex) {
                Logger.getLogger(LoginWindow.class.getName()).log(Level.SEVERE, null, ex);
            }
        }).start();
    }//GEN-LAST:event_registerButton_actionPerformed

